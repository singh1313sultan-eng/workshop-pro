// Builds supabase/seed.sql (plain INSERTs) from the app's data, using the same
// mapping the server uses. Not needed for normal use: the server loads the sample
// data into an empty Supabase database by itself.
//   node supabase/build-seed.js            -> sample data (server/seed.js)
//   node supabase/build-seed.js --current  -> your current data/db.json
const fs = require('fs');
const path = require('path');
const seed = require('../server/seed.js');
const { migrate } = require('../server/masters.js');
const { toRows, TABLE_ORDER } = require('../server/store/mapping.js');

const dbFile = path.join(__dirname, '..', 'data', 'db.json');
const db = process.argv.includes('--current') && fs.existsSync(dbFile) ? JSON.parse(fs.readFileSync(dbFile, 'utf8')) : seed();
migrate(db, seed());
const tables = toRows(db);

const q = (v) => {
  if (v === undefined || v === null) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const out = ['-- Generated by supabase/build-seed.js. Run after schema.sql.', 'begin;', 'set constraints all deferred;'];
for (const t of TABLE_ORDER) {
  const rows = tables[t] || [];
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  out.push(`insert into ${t} (${cols.join(', ')}) values`);
  out.push(rows.map((r) => `  (${cols.map((c) => q(r[c])).join(', ')})`).join(',\n') + ';');
}
out.push('commit;');
const file = path.join(__dirname, 'seed.sql');
fs.writeFileSync(file, out.join('\n') + '\n');
console.log(`Wrote ${file}`);
